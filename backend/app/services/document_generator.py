BASE_DIR = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
FONT_DIR = os.path.join(BASE_DIR, "app", "fonts")
FONT_PATH = os.path.join(FONT_DIR, "Roboto-Regular.ttf")
FONT_BOLD_PATH = os.path.join(FONT_DIR, "Roboto-Bold.ttf")


class DocumentGenerator:
    # =========================================================================
    # ГЕНЕРАЦИЯ PDF
    # =========================================================================
    def _make_pdf(self, title: str, sections: list[dict]) -> bytes:
        pdf = FPDF()
        pdf.add_page()
        pdf.add_font('Roboto', '', FONT_PATH, uni=True)
        pdf.add_font('Roboto', 'B', FONT_BOLD_PATH, uni=True)

        pdf.set_font('Roboto', 'B', 14)
        pdf.multi_cell(0, 8, title, align='C')
        pdf.ln(4)

        pdf.set_font('Roboto', '', 10)
        today = datetime.now().strftime('%d.%m.%Y')
        pdf.cell(0, 6, f"г. Москва, {today}", align='R', new_x="LMARGIN", new_y="NEXT")
        pdf.ln(4)

        for section in sections:
            stype = section.get("type", "text")
            content = section.get("content", "")

            if stype == "subtitle":
                pdf.set_font('Roboto', 'B', 12)
                pdf.ln(2)
                pdf.multi_cell(0, 7, content)
                pdf.ln(1)
            elif stype == "text":
                pdf.set_font('Roboto', '', 11)
                pdf.multi_cell(0, 6, content)
                pdf.ln(1)
            elif stype == "item":
                pdf.set_font('Roboto', '', 11)
                pdf.set_x(15)
                pdf.multi_cell(0, 6, content)
                pdf.ln(0.5)
            elif stype == "sign":
                pdf.ln(4)
                pdf.set_font('Roboto', '', 11)
                pdf.multi_cell(0, 6, content)

        return pdf.output()

    # =========================================================================
    # ГЕНЕРАЦИЯ WORD
    # =========================================================================
    def _make_docx(self, title: str, sections: list[dict]) -> bytes:
        doc = Document()

        style = doc.styles['Normal']
        font = style.font
        font.name = 'Times New Roman'
        font.size = Pt(12)

        title_para = doc.add_paragraph()
        title_para.alignment = WD_ALIGN_PARAGRAPH.CENTER
        run = title_para.add_run(title)
        run.bold = True
        run.font.size = Pt(14)

        today = datetime.now().strftime('%d.%m.%Y')
        date_para = doc.add_paragraph()
        date_para.alignment = WD_ALIGN_PARAGRAPH.RIGHT
        date_run = date_para.add_run(f"г. Москва, {today}")
        date_run.font.size = Pt(10)

        doc.add_paragraph()

        for section in sections:
            stype = section.get("type", "text")
            content = section.get("content", "")

            if stype == "subtitle":
                p = doc.add_paragraph()
                run = p.add_run(content)
                run.bold = True
                run.font.size = Pt(12)
                p.paragraph_format.space_before = Pt(12)
                p.paragraph_format.space_after = Pt(6)
            elif stype == "text":
                p = doc.add_paragraph(content)
                p.paragraph_format.space_after = Pt(6)
            elif stype == "item":
                p = doc.add_paragraph(content)
                p.paragraph_format.left_indent = Cm(1.25)
                p.paragraph_format.space_after = Pt(3)
            elif stype == "sign":
                doc.add_paragraph()
                for line in content.split('\n'):
                    p = doc.add_paragraph(line)
                    p.paragraph_format.space_after = Pt(3)

        buffer = BytesIO()
        doc.save(buffer)
        buffer.seek(0)
        return buffer.getvalue()

